#!/usr/bin/env python3
"""Render docs/event-issue-index.md from planning/issues.yml."""

from __future__ import annotations

from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "planning" / "issues.yml"
OUTPUT = ROOT / "docs" / "event-issue-index.md"


def main() -> None:
    data = yaml.safe_load(MANIFEST.read_text(encoding="utf-8"))
    issues = data["issues"]

    lines = [
        "# Git Together issue index",
        "",
        "Generated from [`planning/issues.yml`](../planning/issues.yml) by",
        "`python3 scripts/render_issue_index.py`. Do not edit this file by hand.",
        "",
        "These 150 issues are the contributor work for **Git Together**. Each person",
        "claims one issue and opens one pull request. Estimated times include reading",
        "and running the acceptance command.",
        "",
        "`no-code` means no programming is required; the issue edits Markdown, YAML,",
        "CSS, or a config file. See [the no-code track](event-no-code-track.md).",
        "",
        "Back to the [event guide](event-guide.md).",
        "",
    ]

    for set_info in data["sets"]:
        slug = set_info["id"]
        set_issues = [issue for issue in issues if issue["set"] == slug]
        areas = Counter(issue["area"] for issue in set_issues)
        difficulty = Counter(issue["difficulty"] for issue in set_issues)
        minutes = sum(issue["estimated_time_minutes"] for issue in set_issues)
        lines.extend(
            [
                f"## {set_info['name']} ({slug})",
                "",
                f"**Focus:** {set_info['focus']}",
                "",
                f"**Issues:** {len(set_issues)} · **Estimated total:** {minutes} minutes",
                "",
                "**Areas:** "
                + ", ".join(f"{name} ({count})" for name, count in sorted(areas.items()))
                + " · **Difficulty:** "
                + ", ".join(f"{name} ({count})" for name, count in sorted(difficulty.items())),
                "",
                "| ID | Issue | Area | Difficulty | Track | Time |",
                "| :--- | :--- | :--- | :--- | :--- | ---: |",
            ]
        )
        for issue in set_issues:
            title = issue["title"].replace("|", "\\|")
            lines.append(
                f"| `{issue['id']}` | {title} | {issue['area']} | {issue['difficulty']} | "
                f"{issue['track']} | {issue['estimated_time']} |"
            )
        lines.append("")

    no_code = [issue for issue in issues if issue["track"] == "no-code"]
    lines.extend(
        [
            "## No-code track",
            "",
            f"**{len(no_code)} issues** require no programming. They still require Git,",
            "careful reading, and the ability to follow terminal instructions.",
            "",
            "| ID | Issue | Area | Time |",
            "| :--- | :--- | :--- | ---: |",
        ]
    )
    for issue in no_code:
        title = issue["title"].replace("|", "\\|")
        lines.append(
            f"| `{issue['id']}` | {title} | {issue['area']} | {issue['estimated_time']} |"
        )
    lines.append("")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(issues)} issues)")


if __name__ == "__main__":
    main()
